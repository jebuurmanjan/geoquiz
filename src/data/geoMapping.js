// Reverse lookup: Dutch name → ISO numeric code string
export const dutchToIsoNum = Object.fromEntries(
  Object.entries(isoNumToDutch).map(([k, v]) => [v, k])
)

// Set of Dutch names that are present in the topojson (for pool filtering)
export const countriesInMap = new Set(Object.values(isoNumToDutch))

// Resolve geo → Dutch name (handles Kosovo edge case)
export function geoDutchName(geo) {
  if (geo.id) return isoNumToDutch[geo.id] || null
  if (geo.properties?.name === 'Kosovo') return 'Kosovo'
  return null
}
